#!/bin/bash
set -euo pipefail

# Deploy Scheduler through Fleet. The cluster runs whatever fleet/infra/scheduler/scheduler.yaml in
# rockfordlhotka/lhotkalake-k8s says. This script regenerates that file from the manifests here (configmap,
# deployment, service, ingress) with the image tag filled in, and opens a PR there. Merging the PR is the deploy:
# Fleet applies it, and the pod's migrate init container applies migrations before the app starts.
#
# Usage: ./deploy.sh <tag>            e.g. ./deploy.sh 1.0.4   (an image pushed by ./build.sh)
#        ./deploy.sh --print <tag>    print the generated file instead (to diff against the bundle)
#
# LHOTKALAKE_K8S: a clone of lhotkalake-k8s (default: ../../lhotkalake-k8s from this repo's root). The script works in a
# temporary worktree, so your checkout there is left as it is. KUBE_CONTEXT defaults to lhotkalake.
# The secrets scheduler-app and scheduler-identity must exist first: see docs/deployment.md.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"

PRINT_ONLY=false
if [[ "${1:-}" == "--print" ]]; then
    PRINT_ONLY=true
    shift
fi
TAG="${1:?Usage: ./deploy.sh <tag>, e.g. ./deploy.sh 1.0.4 (or ./deploy.sh --print <tag>)}"

IMAGE="rockylhotka/scheduler:$TAG"
FLEET_REPO="${LHOTKALAKE_K8S:-$REPO_ROOT/../../lhotkalake-k8s}"
FLEET_GITHUB=rockfordlhotka/lhotkalake-k8s
BUNDLE_FILE=fleet/infra/scheduler/scheduler.yaml
CONTEXT="${KUBE_CONTEXT:-lhotkalake}"
NS=scheduler

render() {
    cat <<'HEADER'
# Scheduler (rdl/scheduler, MarimerLLC/scheduler): MCP server + Blazor UI + outbound email, public through
# Tailscale Funnel at https://scheduler.tail920062.ts.net. See README.md next to this file.
#
# GENERATED by k8s/deploy.sh in rdl/scheduler from its k8s/ manifests: change them there, not here. The two secrets,
# scheduler-app and scheduler-identity, are NOT here: they are made by hand with k8s/create-secrets.sh there.
HEADER
    for manifest in configmap deployment service ingress; do
        echo "---"
        sed "s/IMAGE_TAG/$TAG/g" "$SCRIPT_DIR/$manifest.yaml"
        echo
    done
}

if $PRINT_ONLY; then
    render
    exit 0
fi

die() { echo "$*" >&2; exit 1; }

[[ -d "$FLEET_REPO/.git" ]] || die "No lhotkalake-k8s clone at $FLEET_REPO. Set LHOTKALAKE_K8S."
[[ -z "$(git -C "$REPO_ROOT" status --porcelain -- k8s)" ]] || die "k8s/ has uncommitted changes; commit them first."
docker manifest inspect "$IMAGE" >/dev/null 2>&1 || die "$IMAGE isn't on Docker Hub. Run ./build.sh $TAG first."
for secret in scheduler-app scheduler-identity; do
    kubectl --context "$CONTEXT" get secret "$secret" -n $NS >/dev/null 2>&1 \
        || die "Secret $secret is missing in namespace $NS on $CONTEXT. See docs/deployment.md, step 3."
done

echo "Running now: $(kubectl --context "$CONTEXT" get deployment scheduler -n $NS -o jsonpath='{.spec.template.spec.containers[0].image}' 2>/dev/null || echo 'nothing')"
echo "Deploying:   $IMAGE (from $(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD) at $(git -C "$REPO_ROOT" rev-parse --short HEAD))"
echo "Open scheduler PRs (a build without them rolls them back if one is live):"
gh pr list --repo MarimerLLC/scheduler || true
read -r -p "Open a lhotkalake-k8s PR that deploys $IMAGE? [y/N] " answer
[[ "$answer" == [yY] ]] || exit 1

BRANCH="scheduler-$TAG"
WORKTREE="$(mktemp -d)"
cleanup() { git -C "$FLEET_REPO" worktree remove --force "$WORKTREE" >/dev/null 2>&1 || true; }
trap cleanup EXIT

git -C "$FLEET_REPO" fetch -q origin main
git -C "$FLEET_REPO" worktree add -q -b "$BRANCH" "$WORKTREE" origin/main
render > "$WORKTREE/$BUNDLE_FILE"
if git -C "$WORKTREE" diff --quiet -- "$BUNDLE_FILE"; then
    git -C "$FLEET_REPO" branch -q -D "$BRANCH" 2>/dev/null || true
    die "The bundle already says $IMAGE with these manifests; nothing to deploy."
fi

git -C "$WORKTREE" add "$BUNDLE_FILE"
git -C "$WORKTREE" commit -q -m "scheduler: deploy $TAG" \
    -m "Generated by rdl/scheduler k8s/deploy.sh at $(git -C "$REPO_ROOT" rev-parse --short HEAD)."
git -C "$WORKTREE" push -q -u origin "$BRANCH"
(cd "$WORKTREE" && gh pr create --repo "$FLEET_GITHUB" --base main --head "$BRANCH" \
    --title "scheduler: deploy $TAG" \
    --body "Deploys \`$IMAGE\` (generated by rdl/scheduler \`k8s/deploy.sh\`). Merge to deploy: Fleet applies it, the \`migrate\` init container runs migrations, then the app starts.")

echo ""
echo "Merge that PR to deploy. Then watch it:"
echo "  kubectl --context $CONTEXT -n $NS get pods -w"
echo "  kubectl --context $CONTEXT -n $NS logs deploy/scheduler -c migrate"
echo "  curl -s https://scheduler.tail920062.ts.net/.well-known/oauth-protected-resource/mcp"
